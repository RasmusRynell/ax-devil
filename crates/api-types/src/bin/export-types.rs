//! Writes the Rust API types and the playback constants to frontend/src/generated/api.ts and the API and shell
//! versions to desktop/generated/api.json, only when they changed.

use ts_rs::TS;

/// The exported declarations of the listed types, in order.
macro_rules! declarations {
    ($($type:ty),+ $(,)?) => {
        vec![$(declaration(<$type>::export_to_string()?)),+]
    };
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    use ::playback::ClockIntent;
    use api_types::{playback::*, workspace::*, *};
    use foundation::ErrorCode;
    use sessions::{
        CursorOptions, EndReason, SeatMode, SeatRole,
        session::{
            Access, Can, ContentRef, Control, Refusal, RosterEntry, Sidebar, SidebarView, View,
            ViewerView,
        },
    };
    let mut sections = declarations![
        Grant,
        AppInfo,
        Settings,
        ApiError,
        ErrorCode,
        ErrorParams,
        ErrorWire,
        SidebarView,
        Access,
        ClockIntent,
        Sidebar,
        ViewerView,
        View,
        CursorOptions,
        SessionAuth,
        DocCommand,
        Control,
        ContentRef,
        SessionCommand,
        CursorRegion,
        CursorElement,
        CursorPoint,
        SessionClientMessage,
        SeatRole,
        SeatMode,
        SeatAccess,
        Can,
        RosterEntry,
        SharingInfo,
        DocWire,
        Refusal,
        AckOutcome,
        EndReason,
        SessionServerMessage,
        SessionSummary,
        WorkspaceState,
        ItemState,
        ResolutionState,
        ContentInfo,
        NewItem,
        Direction,
        Want,
        ClientMessage,
        ServerMessage,
    ];
    sections.push(constants());
    let text = format!(
        "// Generated from crates/api-types by make; do not edit.\n// This file was generated by [ts-rs](https://github.com/Aleph-Alpha/ts-rs). Do not edit this file manually.\n\n{}\n",
        sections.join("\n\n")
    );
    write_if_changed("frontend/src/generated/api.ts", &text)?;
    // The desktop shell and the development supervisor are CommonJS and read the versions from JSON.
    let version = format!(
        "{{ \"apiVersion\": {}, \"shellApi\": {} }}\n",
        API_VERSION, SHELL_API
    );
    write_if_changed("desktop/generated/api.json", &version)?;
    Ok(())
}

/// The playback constants as TypeScript consts, each under its doc comment.
fn constants() -> String {
    api_types::playback::CONSTANTS
        .iter()
        .map(|(name, value, doc)| {
            format!(
                "/**\n *{}\n */\nexport const {name} = {value};",
                doc.trim_end().replace('\n', "\n *")
            )
        })
        .collect::<Vec<_>>()
        .join("\n\n")
}

/// Drops what ts-rs puts above every type and the file keeps once: the generator comment and the per-type imports,
/// which are unnecessary because every type lands in the same file.
fn declaration(exported: String) -> String {
    exported
        .lines()
        .filter(|line| !line.starts_with("import type "))
        .skip_while(|line| line.starts_with("//") || line.is_empty())
        .collect::<Vec<_>>()
        .join("\n")
}

fn write_if_changed(path: &str, text: &str) -> std::io::Result<()> {
    let destination = format!("{}/../../{path}", env!("CARGO_MANIFEST_DIR"));
    if std::fs::read_to_string(&destination).ok().as_deref() == Some(text) {
        return Ok(());
    }
    if let Some(folder) = std::path::Path::new(&destination).parent() {
        std::fs::create_dir_all(folder)?;
    }
    std::fs::write(destination, text)
}
