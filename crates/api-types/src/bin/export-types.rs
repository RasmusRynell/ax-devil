//! desktop/generated/api.json, only when they changed.

use ts_rs::TS;

/// The exported declarations of the listed types, in order.
macro_rules! declarations {
    ($($type:ty),+ $(,)?) => {
        vec![$(declaration(<$type>::export_to_string()?)),+]
    };
}

