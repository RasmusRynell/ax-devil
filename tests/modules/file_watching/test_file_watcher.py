"""The file watcher reports each registered file that changed, once, however it was written."""

from __future__ import annotations

import os
import threading
from collections.abc import Callable
from pathlib import Path

import pytest
from pytestqt.qtbot import QtBot

from ax_devil.core.source_paths import SourcePaths
from ax_devil.modules.background_jobs import BackgroundJobs
from ax_devil.modules.file_watching import FileWatcher
from tests.helpers.workspace import wait_for_background_work


def _watch(qtbot: QtBot, paths: SourcePaths) -> tuple[FileWatcher, list[frozenset[Path]]]:
    """Return a watcher of *paths* whose baseline is taken, and the list its reports are appended to."""
    watcher = FileWatcher(quiet_ms=50, jobs=BackgroundJobs(max_workers=2))
    reports: list[frozenset[Path]] = []
    watcher.changed.connect(lambda _key, changed: reports.append(changed))
    threads = set(threading.enumerate())
    watcher.watch("item", paths)
    wait_for_background_work(qtbot, threads)
    return watcher, reports


def _wait_for_reports(qtbot: QtBot, reports: list[frozenset[Path]], count: int) -> None:
    """Wait for *count* reports, then see that no more follow."""
    qtbot.waitUntil(lambda: len(reports) >= count, timeout=5000)
    qtbot.wait(300)


def _rewrite(path: Path) -> None:
    path.write_text("rewritten in place")


def _replace(path: Path) -> None:
    temporary = path.with_name("regenerated.tmp")
    temporary.write_text("regenerated by another file replacing it")
    os.replace(temporary, path)


@pytest.mark.parametrize("write", [_rewrite, _replace], ids=["in-place", "replaced-by-rename"])
def test_a_rewritten_file_is_reported_once_and_still_watched_afterwards(
    qtbot: QtBot, tmp_path: Path, write: Callable[[Path], None]
) -> None:
    detections = tmp_path / "det.txt"
    detections.write_text("first")
    _watcher, reports = _watch(qtbot, SourcePaths(files=frozenset({detections})))
    (tmp_path / "unrelated.txt").write_text("not registered")

    write(detections)
    _wait_for_reports(qtbot, reports, 1)
    assert reports == [frozenset({detections})]

    detections.write_text("and rewritten once more")
    _wait_for_reports(qtbot, reports, 2)
    assert reports == [frozenset({detections})] * 2


def test_a_file_added_to_a_watched_folder_is_reported_as_the_folder_changing(qtbot: QtBot, tmp_path: Path) -> None:
    (tmp_path / "images" / "seq1").mkdir(parents=True)
    _watcher, reports = _watch(qtbot, SourcePaths(folders=frozenset({tmp_path / "images"})))

    (tmp_path / "images" / "seq1" / "000001.jpg").write_text("frame")

    _wait_for_reports(qtbot, reports, 1)
    assert reports == [frozenset({tmp_path / "images" / "seq1"})]


def test_a_file_rewritten_in_place_inside_a_watched_folder_is_deliberately_not_reported(
    qtbot: QtBot, tmp_path: Path
) -> None:
    (tmp_path / "images").mkdir()
    frame = tmp_path / "images" / "000001.jpg"
    frame.write_text("frame")
    _watcher, reports = _watch(qtbot, SourcePaths(folders=frozenset({tmp_path / "images"})))

    _rewrite(frame)
    (tmp_path / "images" / "000002.jpg").write_text("another frame")

    _wait_for_reports(qtbot, reports, 1)
    assert reports == [frozenset({tmp_path / "images"})]


def test_watching_more_paths_keeps_the_baseline_so_a_change_made_meanwhile_is_reported(
    qtbot: QtBot, tmp_path: Path
) -> None:
    detections = tmp_path / "det.txt"
    detections.write_text("first")
    other = tmp_path / "other.txt"
    other.write_text("new to the watcher")
    watcher, reports = _watch(qtbot, SourcePaths(files=frozenset({detections})))

    _rewrite(detections)
    watcher.watch("item", SourcePaths(files=frozenset({detections, other})))

    _wait_for_reports(qtbot, reports, 1)
    assert reports == [frozenset({detections})]


def test_a_file_that_does_not_exist_yet_is_reported_when_it_appears(qtbot: QtBot, tmp_path: Path) -> None:
    detections = tmp_path / "later" / "deeper" / "det.txt"
    _watcher, reports = _watch(qtbot, SourcePaths(files=frozenset({detections})))

    detections.parent.mkdir(parents=True)
    detections.write_text("generated")

    _wait_for_reports(qtbot, reports, 1)
    assert reports == [frozenset({detections})]
